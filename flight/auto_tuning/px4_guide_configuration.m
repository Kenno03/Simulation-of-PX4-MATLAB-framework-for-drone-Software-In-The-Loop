function [cfg,Groups]=px4_guide_configuration(request,options)
%PX4_GUIDE_CONFIGURATION Loop groups for guide-based tuning. Every flight excites all axes of
% one group in sequence (multi-axis TestAxis code), so one takeoff serves all axes.
arguments
    request (1,:) string = "all"
    options.MaxHours (1,1) double = 24
    options.Repeats (1,1) double = 3
    options.MaxFlightsPerGroup (1,1) double = 20
end
available=[group("rates","Rates",1,[1 2 3],0.15, ...
        ["Roll rate","Pitch rate","Yaw rate"],["rollrate","pitchrate","yawrate"], ...
        {struct('K',"MC_ROLLRATE_K",'P',"MC_ROLLRATE_P",'I',"MC_ROLLRATE_I",'D',"MC_ROLLRATE_D"), ...
         struct('K',"MC_PITCHRATE_K",'P',"MC_PITCHRATE_P",'I',"MC_PITCHRATE_I",'D',"MC_PITCHRATE_D"), ...
         struct('K',"MC_YAWRATE_K",'P',"MC_YAWRATE_P",'I',"MC_YAWRATE_I",'D',"MC_YAWRATE_D")}), ...
     group("attitude","Attitude",2,[1 2 3],0.10, ...
        ["Roll attitude","Pitch attitude","Yaw attitude"],["rollattitude","pitchattitude","yawattitude"], ...
        {struct('P',"MC_ROLL_P"),struct('P',"MC_PITCH_P"),struct('P',"MC_YAW_P")}), ...
     group("velocity","Velocity",3,[1 3],0.80, ...
        ["Horizontal velocity","Vertical velocity"],["horizontalvelocity","verticalvelocity"], ...
        {struct('P',"MPC_XY_VEL_P_ACC",'I',"MPC_XY_VEL_I_ACC",'D',"MPC_XY_VEL_D_ACC"), ...
         struct('P',"MPC_Z_VEL_P_ACC",'I',"MPC_Z_VEL_I_ACC",'D',"MPC_Z_VEL_D_ACC")}), ...
     group("position","Position",4,[1 3],0.80, ...
        ["Horizontal position","Vertical position"],["horizontalposition","verticalposition"], ...
        {struct('P',"MPC_XY_P"),struct('P',"MPC_Z_P")})];
if isequal(request,"all"),Groups=available;else
    Groups=available([]);
    for key=lower(request)
        i=find([available.Key]==key);assert(isscalar(i),'Unknown loop group: %s (rates, attitude, velocity, position).',key);
        Groups(end+1)=available(i); %#ok<AGROW>
    end
end
cfg=struct('Plant','Drone_simulation_PX4','PX4Model','PX4_Receive','RunMode',"guide",'SessionMode',true, ...
    'StageLimit',numel(Groups),'SimTime',110,'TestStart',40,'ExpectedSteps',10,'MinimumSteps',5, ...
    'MaxTrials',options.MaxFlightsPerGroup,'BudgetSec',options.MaxHours*3600,'ObjectiveVersion',"joint_response_v1", ...
    'MaxWallPerRun',2700,'MinRemainingToStart',60,'HoverThrust',single(hoverThrust()),'HomeNED',single([0 0 -10]), ...
    'MinTestAltitude',2,'MinAltitude',2,'MaxReadyClimbRate',1,'MaxBodyRate',5,'MaxRecoveryRate',5, ...
    'Repeats',options.Repeats,'ShowFigures',false,'GuideVersion',"guide_v1");
for k=1:numel(Groups)
    [~,~,duration]=px4_tuning_step_windows(Groups(k).Mode);
    Groups(k).SegmentDuration=duration;
    Groups(k).SimTime=10*ceil((cfg.TestStart+30+numel(Groups(k).Axes)*duration+5)/10);
    for j=1:numel(Groups(k).Axes)
        Groups(k).Members(j).SegmentOffset=(j-1)*duration;
    end
end
cfg.SimTime=max([Groups.SimTime]);
cfg.FlightPlan=flight_plan("square");cfg.FlightPlan.Size=0;cfg.FlightPlan.Altitude=-double(cfg.HomeNED(3));
end

function h=hoverThrust()
% Normalised hover thrust of the current vehicle (PX4 thrust command with THR_MDL_FAC = 1), from the
% workspace built by Main.mlx; 0.3 if no vehicle has been built yet.
h=0.3;
try,SP=evalin('base','SimParams');h=SP.HoverThrustFraction;catch,end
end

function G=group(key,name,mode,axes,amplitude,axisNames,axisKeys,gains)
code=8+sum(2.^(axes-1));members=struct([]);
for j=1:numel(axes)
    m=struct('Key',axisKeys(j),'Name',axisNames(j),'Mode',uint8(mode),'Axis',uint8(axes(j)), ...
        'Amplitude',single(amplitude*px4_tuning_axis_scale(mode,axes(j))),'SegmentOffset',0, ...
        'Gains',gains{j},'MaxTrials',1);
    if isempty(members),members=m;else,members(end+1)=m;end %#ok<AGROW>
end
G=struct('Key',string(key),'Name',string(name),'Mode',uint8(mode),'Axis',uint8(code),'Axes',axes, ...
    'Amplitude',single(amplitude),'Members',members,'MaxTrials',1,'SegmentDuration',NaN,'SimTime',NaN);
end
